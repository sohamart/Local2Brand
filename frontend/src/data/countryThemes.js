export const parseNumericPrice = (priceVal) => {
  if (typeof priceVal === 'number') return priceVal;
  if (!priceVal || typeof priceVal !== 'string') return 0;
  const numStr = priceVal.replace(/[^0-9.]/g, '');
  return parseFloat(numStr) || 0;
};

export const formatPriceByCountry = (priceVal, country = 'India') => {
  const numericInr = parseNumericPrice(priceVal);
  const theme = COUNTRY_CULTURAL_THEMES[country] || COUNTRY_CULTURAL_THEMES['India'] || COUNTRY_CULTURAL_THEMES['Other'];
  const rate = theme.exchangeRate || 1;
  const converted = Math.round(numericInr * rate);
  return `${theme.symbol || '₹'}${converted.toLocaleString()}`;
};


export const resolveCategoryFromTemplate = (templateNameOrSlug) => {
  if (!templateNameOrSlug || typeof templateNameOrSlug !== 'string') return '';
  const s = templateNameOrSlug.toLowerCase();
  
  if (s.includes('dining') || s.includes('restaurant') || s.includes('food') || s.includes('nawabi') || s.includes('biryani') || s.includes('dish') || s.includes('table reservation') || s.includes('cuisine')) {
    return 'restaurant';
  }
  if (s.includes('cafe') || s.includes('coffee') || s.includes('bakery') || s.includes('bistro') || s.includes('brew')) {
    return 'cafe';
  }
  if (s.includes('salon') || s.includes('spa') || s.includes('beauty') || s.includes('parlour') || s.includes('hair') || s.includes('stylist')) {
    return 'salon';
  }
  if (s.includes('gym') || s.includes('fitness') || s.includes('workout') || s.includes('crossfit') || s.includes('muscle')) {
    return 'gym';
  }
  if (s.includes('hotel') || s.includes('resort') || s.includes('stay') || s.includes('lodge') || s.includes('room') || s.includes('villa')) {
    return 'hotel';
  }
  if (s.includes('estate') || s.includes('property') || s.includes('realtor') || s.includes('apartment') || s.includes('builder')) {
    return 'real_estate';
  }
  if (s.includes('photo') || s.includes('wedding') || s.includes('studio') || s.includes('camera') || s.includes('cinematography')) {
    return 'photography';
  }
  if (s.includes('boutique') || s.includes('cloth') || s.includes('fashion') || s.includes('apparel') || s.includes('wear') || s.includes('saree')) {
    return 'boutique';
  }
  if (s.includes('coach') || s.includes('lms') || s.includes('course') || s.includes('institute') || s.includes('academy') || s.includes('tutor') || s.includes('class')) {
    return 'coaching';
  }
  if (s.includes('clinic') || s.includes('doctor') || s.includes('dental') || s.includes('hospital') || s.includes('medical') || s.includes('dentist') || s.includes('health')) {
    return 'clinic';
  }
  if (s.includes('jewel') || s.includes('gift') || s.includes('gold') || s.includes('diamond') || s.includes('ornament') || s.includes('watch')) {
    return 'jewellery';
  }
  if (s.includes('showroom') || s.includes('auto') || s.includes('car') || s.includes('bike') || s.includes('vehicle') || s.includes('motor')) {
    return 'showroom';
  }
  return '';
};
